export function resolveLang(search, stored) {
  let q = null;
  try {
    q = new URLSearchParams(search || '').get('lang');
  } catch {
    q = null;
  }
  if (q === 'pt' || q === 'en') return q;
  return stored === 'pt' ? 'pt' : 'en';
}
